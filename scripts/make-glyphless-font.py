"""
Writes the font Tessel's invisible text layer is set in (src/core/engine/pdfium/glyphless.ts): every glyph empty and
of one width, one glyph per character, so copied and searched text comes back as it was recognised while the file
grows by a few kilobytes only. Needs fontTools: python3 -m pip install fonttools; python3 scripts/make-glyphless-font.py
"""
import base64
import io
import pathlib

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

# Latin (with its extensions), Greek, Cyrillic, punctuation, currency, letterlike symbols, arrows, maths, ligatures.
RANGES = [(0x20, 0x7E), (0xA0, 0x24F), (0x370, 0x3FF), (0x400, 0x4FF), (0x1E00, 0x1EFF), (0x2000, 0x206F), (0x20A0, 0x20CF), (0x2100, 0x214F), (0x2190, 0x21FF), (0x2200, 0x22FF), (0xFB00, 0xFB06)]
WIDTH = 500
codes = [c for a, b in RANGES for c in range(a, b + 1)]
names = [".notdef"] + [f"g{c:04X}" for c in codes]

fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(names)
fb.setupCharacterMap({c: f"g{c:04X}" for c in codes})
empty = TTGlyphPen(None).glyph()
fb.setupGlyf({n: empty for n in names})
fb.setupHorizontalMetrics({n: (WIDTH, 0) for n in names})
fb.setupHorizontalHeader(ascent=800, descent=-200)
fb.setupNameTable({"familyName": "TesselText", "styleName": "Regular"})
fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200)
fb.setupPost()
out = io.BytesIO()
fb.save(out)
data = out.getvalue()
b64 = base64.b64encode(data).decode()
target = pathlib.Path(__file__).resolve().parent.parent / "src/core/engine/pdfium/glyphless.ts"
target.write_text(
    "// Generated by scripts/make-glyphless-font.py: an invisible font, every character an empty glyph of one width.\n"
    f"export const GLYPHLESS_WIDTH = {WIDTH} / 1000;\n"
    f"export const GLYPHLESS = '{b64}';\n"
)
print(len(data), "bytes,", len(codes), "characters")
